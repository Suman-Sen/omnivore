import {test,expect} from '@playwright/test';
const password='synthetic-profile-password';
test('PROF-001..005/007 THEME-001: create, persist, lock, switch and reject wrong password',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Profile name',{exact:true}).fill('Profile A');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await expect(page.getByTestId('active-profile')).toContainText('Profile A');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  for(const name of ['Solid','High contrast','Glass','Solid']){
    await page.getByRole('radio',{name,exact:false}).check();
    await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
    await expect(page.getByRole('radio',{name,exact:false})).toBeChecked();
  }
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.getByText('Customize dashboard',{exact:true}).click();
  await page.getByRole('checkbox',{name:'Enable Journal module',exact:true}).uncheck();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
  await expect(page.getByRole('button',{name:'Journal',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Move goals up',exact:true}).click();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Unlock your profile'})).toBeVisible();
  await page.getByLabel('Password',{exact:true}).fill('wrong password');
  await page.getByRole('button',{name:'Unlock profile',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'Unable to unlock'})).toContainText('Unable to unlock');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Unlock profile',exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await expect(page.getByRole('radio',{name:'Solid',exact:false})).toBeChecked();
  await expect(page.getByRole('button',{name:'Journal',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.getByText('Customize dashboard',{exact:true}).click();
  await expect(page.getByText('2. goals',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Lock / switch profile'}).filter({visible:true}).click();
  await page.getByRole('button',{name:'Create another profile'}).click();
  await page.getByLabel('Profile name',{exact:true}).fill('Profile B');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await expect(page.getByTestId('active-profile')).toContainText('Profile B');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await expect(page.getByRole('radio',{name:'Glass',exact:false})).toBeChecked();
  await expect(page.getByRole('button',{name:'Journal',exact:true})).toBeVisible();
  await expect(page.getByTestId('active-profile')).not.toContainText('Profile A');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
