import {test,expect} from '@playwright/test';
const password='synthetic-planning-password';
test('P2 offline task/note/calendar/journal flow and reload',async({page,context})=>{
  await page.goto('/');
  await page.getByLabel('Profile name',{exact:true}).fill('Planner');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await expect(page.getByTestId('active-profile')).toContainText('Planner');
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true}));});
  await context.setOffline(true);
  await page.getByRole('button',{name:'Notes',exact:true}).click();
  await page.getByRole('button',{name:'New note',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('Read chapter');
  await page.getByLabel('Note content').fill('Keep this original note.');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Read chapter',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Convert to task'}).click();
  await page.getByRole('button',{name:'Save task',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Read chapter',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Complete',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reopen',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Calendar',exact:true}).click();
  await page.getByRole('button',{name:'New event',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('Study session');
  await page.getByLabel('Start time',{exact:true}).fill('2026-10-04T10:00');
  await page.getByLabel('End time',{exact:true}).fill('2026-10-04T11:00');
  await page.getByRole('button',{name:'Save event',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Study session',exact:true})).toBeVisible();
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-10-04');
  await page.getByRole('button',{name:'Edit Study session',exact:true}).click();
  await expect(page.getByLabel('Start time',{exact:true})).toHaveValue('2026-10-04T10:00');
  await page.getByLabel('Title',{exact:true}).fill('Revised study session');
  await page.getByRole('button',{name:'Save event',exact:true}).click();
  await expect(page.getByRole('button',{name:'Edit Revised study session',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Journal',exact:true}).click();
  await page.getByRole('button',{name:'New journal',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('My day');
  await page.getByLabel('Your narrative').fill('Family time changed my plans.');
  await page.getByRole('button',{name:'Save journal',exact:true}).click();
  await expect(page.getByRole('button',{name:'Save journal',exact:true})).toHaveCount(0);
  await expect(page.getByText('Family time changed my plans.',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Unlock profile',exact:true}).click();
  await page.getByRole('button',{name:'Tasks',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reopen',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Notes',exact:true}).click();
  await expect(page.getByText('Keep this original note.',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
