import {test,expect} from '@playwright/test';
const password='synthetic-appearance-password';
test('THEME-001..004: custom colors and private image persist offline and reset accessibly',async({page,context})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Profile name',{exact:true}).fill('Custom A');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Create profile',exact:true}).click();
  await expect(page.getByTestId('active-profile')).toContainText('Custom A');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Accent hex color').fill('#FfCC00');
  await page.getByLabel('Background hex color').fill('#123456');
  await page.getByRole('button',{name:'Save colors',exact:true}).click();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
  await expect(page.locator('.workspace')).toHaveCSS('--accent','#ffcc00');
  await expect(page.locator('.workspace')).toHaveCSS('--accent-text','#000000');
  await page.getByLabel('Accent hex color').fill('#oops');
  await page.getByRole('button',{name:'Save colors',exact:true}).click();
  await expect(page.locator('.workspace')).toHaveCSS('--accent','#ffcc00');
  await page.getByLabel('Accent hex color').fill('#ffcc00');
  const data=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=64;canvas.height=64;const ctx=canvas.getContext('2d')!;ctx.fillStyle='#943be2';ctx.fillRect(0,0,64,64);return canvas.toDataURL('image/png').split(',')[1];});
  await page.getByLabel('Background image',{exact:true}).setInputFiles({name:'background.png',mimeType:'image/png',buffer:Buffer.from(data,'base64')});
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Background image saved on this device.');
  await expect(page.locator('.workspace')).toHaveCSS('background-image',/data:image/);
  await expect(page.getByRole('region',{name:'Planning workspace',exact:true,includeHidden:true})).toHaveCSS('background-color','rgba(247, 250, 245, 0.82)');
  await page.getByLabel('Background image',{exact:true}).setInputFiles({name:'invalid.png',mimeType:'image/png',buffer:Buffer.from('not an image')});
  await expect(page.getByRole('alert').filter({hasText:'could not be opened'})).toContainText('could not be opened');
  await expect(page.locator('.workspace')).toHaveCSS('background-image',/data:image/);
  await page.getByRole('radio',{name:'High contrast'}).check();
  await expect(page.locator('.workspace')).toHaveCSS('background-image','none');
  await page.getByRole('radio',{name:'Glass',exact:false}).check();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await context.setOffline(true);await page.reload();
  await expect(page.locator('.workspace')).toHaveCSS('background-image',/radial-gradient/);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Unlock profile',exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await expect(page.getByLabel('Accent hex color')).toHaveValue('#ffcc00');
  await expect(page.locator('.workspace')).toHaveCSS('background-image',/data:image/);
  await page.getByRole('button',{name:'Remove background image'}).click();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Background image removed.');
  await expect(page.locator('.workspace')).toHaveCSS('background-image',/radial-gradient/);
  await page.getByRole('button',{name:'Reset colors',exact:true}).click();
  await expect(page.getByRole('status',{name:'Profile status'})).toHaveText('Settings saved on this device.');
  await expect(page.getByLabel('Accent hex color')).toHaveValue('#264c40');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
